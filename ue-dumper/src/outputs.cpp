bool writeNamesTxt(const std::string& path, const ue::NameDb& names) {
    std::string o;
    o += fmt("; Names.txt - %zu entries - generated by UnrealDumperX %s at %s\n",
             names.all().size(), UDX_VERSION_STRING, timestamp().c_str());
    for (usize i = 0; i < names.all().size(); ++i) {
        o += fmt("[0x%08zX] %s\n", i, names.all()[i].c_str());
        if (o.size() > 32ull * 1024 * 1024) {
            log::warn("Names.txt cok buyuk - kesildi");
            break;
        }
    }
    return writeTextFile(path, o);
}

bool writeObjectsTxt(const std::string& path, Process& proc,
                     const ue::Offsets& off, const ue::ObjectDb& objects,
                     const ue::NameDb& names) {
    const i32 num = objects.count();
    std::string o;
    o += fmt("; Objects.txt - %d objects - generated by UnrealDumperX %s at %s\n",
             num, UDX_VERSION_STRING, timestamp().c_str());

    log::Progress progress("Objects.txt", (u64)num);
    for (i32 i = 0; i < num; ++i) {
        progress.update((u64)i);
        const u64 obj = objects.objectAt(i);
        if (!obj) continue;

        const u32 nameIdx = proc.read<u32>(obj + off.uobjName);
        const std::string name = names.get(nameIdx);
        const u64 cls = proc.read<u64>(obj + off.uobjClass);
        std::string clsName;
        if (cls && proc.ptrReadable(cls))
            clsName = names.get(proc.read<u32>(cls + off.uobjName));

        // Full outer path (bounded).
        std::string pathStr;
        {
            u64 cur = obj;
            for (int d = 0; cur && d < 64; ++d) {
                pathStr.insert(0, "/" + names.get(proc.read<u32>(cur + off.uobjName)));
                cur = proc.read<u64>(cur + off.uobjOuter);
            }
        }
        o += fmt("[0x%08X] 0x%016llX  Class: %-32s Name: %-40s Path: %s\n",
                 i, (unsigned long long)obj, clsName.c_str(), name.c_str(),
                 pathStr.c_str());

        if (o.size() > 256ull * 1024 * 1024) {
            log::warn("Objects.txt sinira ulasti - kesildi");
            break;
        }
    }
    progress.done(fmt("Objects.txt: %d satir", num));
    return writeTextFile(path, o);
}

bool writeOffsetsTxt(const std::string& path, const ue::Offsets& off,
                     UEVersion ver, const std::string& gameName,
                     const std::string& layoutNote) {
    std::string o;
    o += fmt("; offsets.txt - %s (%s) - generated %s\n", gameName.c_str(),
             ue::versionToString(ver), timestamp().c_str());
    o += fmt("; engine: %s   struct layout: %s\n\n", ue::versionToString(ver),
             layoutNote.c_str());
    o += "GObjects = " + toHex(off.gObjects) + "\n";
    o += "GNames   = " + toHex(off.gNames) + "\n";
    o += "GWorld   = " + toHex(off.gWorld) + "\n\n";
    o += "[discovery]\n";
    o += off.describe();
    o += "\n; source tags: ini = games.ini authoritative (never probed),\n";
    o += "; vote = runtime offset discovery (NOTE #5/#7), probe/anchor/known = finder\n";
    return writeTextFile(path, o);
}

bool writeSignaturesTxt(const std::string& path,
                        const std::vector<ue::SigRecord>& sigs,
                        const std::string& title,
                        const std::vector<vt::ResolvedFunc>* funcs) {
    std::string o;
    o += fmt("; %s - generated by UnrealDumperX %s at %s\n", title.c_str(),
             UDX_VERSION_STRING, timestamp().c_str());
    o += "; format: name | module | resolved | main signature | 16-byte extended\n";
    o += "; reuse: put  main|extended  under [Signatures] <name> in games.ini\n\n";

    for (const auto& s : sigs) {
        o += fmt("%s | %s | 0x%016llX | %s | %s\n", s.name.c_str(),
                 s.module.c_str(), (unsigned long long)s.resolved,
                 s.mainSig.c_str(), s.extSig.c_str());
    }
    if (funcs) {
        o += "\n; tracked functions (source tags per NOTE #14):\n";
        for (const auto& f : *funcs) {
            o += fmt("[%s] %s | 0x%016llX | slot=%d | %s\n", f.source.c_str(),
                     f.name.c_str(), (unsigned long long)f.address,
                     f.vtableIndex, f.module.c_str());
        }
    }
    return writeTextFile(path, o);
}

