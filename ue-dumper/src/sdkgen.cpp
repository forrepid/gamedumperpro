// ---------------------------------------------------------------------------
// C++ keyword guard for member names
// ---------------------------------------------------------------------------
bool SdkGenerator::isCppKeyword(const std::string& id) {
    static const char* k[] = {
        "alignas","alignof","auto","bool","break","case","catch","char","class",
        "const","constexpr","continue","default","delete","do","double","else",
        "enum","explicit","extern","false","final","float","for","friend","goto",
        "if","inline","int","long","mutable","namespace","new","nullptr","operator",
        "override","private","protected","public","register","return","short",
        "signed","sizeof","static","struct","switch","template","this","throw",
        "true","try","typedef","typename","union","unsigned","using","virtual",
        "void","volatile","wchar_t","while",
    };
    for (const char* s : k)
        if (id == s) return true;
    return false;
}

std::string SdkGenerator::memberName(const std::string& raw) {
    std::string n = sanitizeIdent(raw);
    if (isCppKeyword(n)) n += "_";
    return n;
}

// ---------------------------------------------------------------------------
// Object walk
// ---------------------------------------------------------------------------
SdkGenerator::SdkGenerator(Process& proc, ue::Offsets& off, ue::NameDb& names,
                           ue::ObjectDb& objects, ue::ClassParser& parser,
                           const SdkOptions& opts)
    : proc_(proc), off_(off), names_(names), objects_(objects),
      parser_(parser), opts_(opts) {}

void SdkGenerator::collect() {
    const i32 num = objects_.count();
    std::set<u64> seen;
    log::Progress progress("SDK koleksiyonu", (u64)num);

    for (i32 i = 0; i < num; ++i) {
        progress.update((u64)i);
        const u64 obj = objects_.objectAt(i);
        if (!obj || !seen.insert(obj).second) continue;

        const std::string kind = parser_.classNameOf(obj);
        if (kind == "Class") {
            auto s = parser_.parseStruct(obj, true);
            if (!s) continue;
            ++classCount_;
            packages_[s->package].push_back(std::move(*s));
        } else if (kind == "ScriptStruct") {
            auto s = parser_.parseStruct(obj, false);
            if (!s) continue;
            ++structCount_;
            packages_[s->package].push_back(std::move(*s));
        } else if (kind == "Enum") {
            auto e = parser_.parseEnum(obj);
            if (!e) continue;
            ++enumCount_;
            enumPackages_[e->package].push_back(std::move(*e));
        }
    }
    progress.done(fmt("SDK koleksiyonu: %zu sinif, %zu struct, %zu enum, %zu paket",
                      classCount_, structCount_, enumCount_, packages_.size()));

    // Index types for cross-package include resolution.
    for (const auto& [pkg, vec] : packages_)
        for (const auto& s : vec)
            packageOfName_[s.name] = pkg;
}

// ---------------------------------------------------------------------------
// Basic.h
// ---------------------------------------------------------------------------
std::string SdkGenerator::basicHeader() const {
    std::string o;
    o += "// ============================================================\n";
    o += "// Basic.h - generated by UnrealDumperX for " + opts_.gameName + "\n";
    o += "// Engine: " + opts_.version + "   Date: " + timestamp() + "\n";
    o += "// ============================================================\n";
    o += "#pragma once\n#include <cstdint>\n#include <cstring>\n\n";
    o += "namespace udxrt {\n\n";
    o += "struct FName { int32_t Index; int32_t Number; };\n";
    o += "template <class T> struct TArray { T* Data; int32_t Num; int32_t Max; };\n";
    o += "struct FString : TArray<wchar_t> {};\n";
    o += "struct FText { uint8_t Unknown[0x10]; };\n\n";
    o += "// Minimal UObject skeleton (layout taken from this dump).\n";
    o += "struct UObjectBase {\n";
    o += "    void*   Vft;\n";
    o += "    int32_t Flags;\n";
    o += "    int32_t InternalIndex;\n";
    o += fmt("    void*   Class;      // 0x%X\n", off_.uobjClass);
    o += fmt("    FName   Name;       // 0x%X\n", off_.uobjName);
    o += fmt("    void*   Outer;      // 0x%X\n", off_.uobjOuter);
    o += "};\n\n";
    o += "// Placeholder function handle - hosts that resolve UFunction pointers\n";
    o += "// replace FindFunction with their own resolver (defaults to a no-op so\n";
    o += "// thunks stay safe when unlinked).\n";
    o += "struct UFunctionPlaceholder;\n";
    o += "inline UFunctionPlaceholder* FindFunction(const char*) { return nullptr; }\n\n";
    o += fmt("constexpr uintptr_t GObjects       = 0x%llX;\n", (unsigned long long)off_.gObjects);
    o += fmt("constexpr int       TuArrayOffset  = 0x%X;\n", off_.tuObjectArrayOffset);
    o += fmt("constexpr int       ItemSize       = 0x%X;\n", off_.objectItemSize);
    o += fmt("constexpr int       ChunkCapacity  = 0x%X;\n", off_.chunkCapacity);
    o += fmt("constexpr int       UObject_Class  = 0x%X;\n", off_.uobjClass);
    o += fmt("constexpr int       UObject_Name   = 0x%X;\n", off_.uobjName);
    o += fmt("constexpr int       UObject_Outer  = 0x%X;\n", off_.uobjOuter);
    o += fmt("constexpr int       ProcessEventIndex = %d;\n", opts_.processEventIndex);
    o += "\nusing ProcessEventFn = void(*)(void* obj, void* func, void* parms);\n\n";
    o += "inline void ProcessEvent(void* obj, void* func, void* parms) {\n";
    o += "    if (ProcessEventIndex < 0 || !obj || !func) return;\n";
    o += "    void** vft = *(void***)obj;\n";
    o += "    reinterpret_cast<ProcessEventFn>(vft[ProcessEventIndex])(obj, func, parms);\n";
    o += "}\n\n";
    o += "} // namespace udxrt\n";
    return o;
}

// ---------------------------------------------------------------------------
// Member emission (IMPORTANT NOTE #15: UnknownData_XX + bitfields)
// ---------------------------------------------------------------------------
std::string SdkGenerator::emitMembers(const StructInfo& s) const {
    std::string o;
    int cur = 0;
    int lastBoolByte = -1;
    for (const auto& p : s.props) {
        const int total = p.size * std::max(p.arrayDim, 1);
        if (p.offset < 0 || p.offset > 0x100000) continue;

        // Bitfields at the same byte keep packing; everything else pads.
        if (!(p.bitfield && p.offset == lastBoolByte) && p.offset > cur) {
            char gap[64];
            snprintf(gap, sizeof(gap), "UnknownData_%04X", cur);
            o += fmt("    uint8 %s[0x%X]; // 0x%X(0x%X)\n", gap, p.offset - cur,
                     cur, p.offset - cur);
        }

        const std::string name = memberName(p.name);
        std::string type = p.type;
        if (p.bitfield) {
            o += fmt("    uint8 %s : 1; // 0x%X(0x01)%s\n", name.c_str(),
                     p.offset, p.comment.empty() ? "" : (" " + p.comment).c_str());
            lastBoolByte = p.offset;
            cur = p.offset + 1;
            continue;
        }
        if (p.arrayDim > 1)
            o += fmt("    %s %s[0x%X]; // 0x%X(0x%X)%s\n", type.c_str(),
                     name.c_str(), p.arrayDim, p.offset, total,
                     p.comment.empty() ? "" : (" " + p.comment).c_str());
        else
            o += fmt("    %s %s; // 0x%X(0x%X)%s\n", type.c_str(), name.c_str(),
                     p.offset, total,
                     p.comment.empty() ? "" : (" " + p.comment).c_str());
        cur = p.offset + total;
        lastBoolByte = -1;
    }
    // Trailing padding up to the declared class size.
    if (s.size > cur && cur > 0) {
        o += fmt("    uint8 UnknownData_%04X[0x%X]; // 0x%X(0x%X)\n", cur,
                 s.size - cur, cur, s.size - cur);
    }
    return o;
}

// ---------------------------------------------------------------------------
// Function emission (ProcessEvent thunks)
// ---------------------------------------------------------------------------
std::string SdkGenerator::emitFunctions(const StructInfo& s) const {
    std::string o;
    for (const auto& f : s.funcs) {
        if (f.name.empty()) continue;
        // Params struct
        std::string params;
        for (const auto& p : f.params) {
            if (p.returnParam) continue;
            params += fmt("    %s %s; // 0x%X(0x%X)%s\n", p.type.c_str(),
                          memberName(p.name).c_str(), p.offset,
                          p.size * std::max(p.arrayDim, 1),
                          p.outParam ? " (out)" : "");
        }
        o += fmt("    // %s  flags=0x%X %s\n", f.fullName.c_str(), f.flags,
                 f.func ? "" : "(no native)");
        o += fmt("    struct %s_Parms {\n", f.name.c_str());
        if (params.empty()) o += "        // no parameters\n";
        else o += params;
        o += "    };\n\n";

        // Signature
        std::string sig, body, copies;
        for (const auto& p : f.params) {
            if (p.returnParam) continue;
            if (!sig.empty()) sig += ", ";
            sig += fmt("%s %s%s", p.type.c_str(), memberName(p.name).c_str(),
                       p.outParam ? "*" : "");
            if (p.outParam) copies += fmt("    *%s = parms.%s;\n",
                                          memberName(p.name).c_str(),
                                          memberName(p.name).c_str());
        }
        const std::string ret = f.returnType.empty() ? "void" : f.returnType;
        std::string retCopy;
        for (const auto& p : f.params)
            if (p.returnParam)
                retCopy = fmt("    return parms.%s;\n", memberName(p.name).c_str());

        o += fmt("    %s %s(%s);\n\n", ret.c_str(), memberName(f.name).c_str(),
                 sig.c_str());

        if (!opts_.eventThunks) continue;
        o += fmt("    inline %s %s(%s)\n    {\n", ret.c_str(),
                 memberName(f.name).c_str(), sig.c_str());
        o += fmt("        static udxrt::UFunctionPlaceholder* fn = udxrt::FindFunction(\"%s\");\n",
                 f.fullName.c_str());
        o += fmt("        %s_Parms parms{};\n", f.name.c_str());
        for (const auto& p : f.params) {
            if (p.returnParam || p.outParam) continue;
            o += fmt("        parms.%s = %s;\n", memberName(p.name).c_str(),
                     memberName(p.name).c_str());
        }
        o += "        udxrt::ProcessEvent(this, fn, &parms);\n";
        o += copies;
        o += retCopy;
        o += "    }\n\n";
    }
    return o;
}

// ---------------------------------------------------------------------------
// Per-package files
// ---------------------------------------------------------------------------
std::string SdkGenerator::emitClassesFile(const std::string& pkg) const {
    const auto& vec = packages_.at(pkg);
    std::string o;
    o += "#pragma once\n";
    o += fmt("// Generated by UnrealDumperX - package \"%s\" (%d classes)\n",
             pkg.c_str(), (int)vec.size());
    o += fmt("// Game: %s  Engine: %s\n\n", opts_.gameName.c_str(),
             opts_.version.c_str());
    o += "#include \"../Basic.h\"\n";

    std::set<std::string> includes;
    for (const auto& s : vec) {
        if (s.superPackage.empty() || s.superPackage == pkg) continue;
        includes.insert(fmt("#include \"../%s/%s_classes.h\"", s.superPackage.c_str(),
                            sanitizeIdent(s.superPackage).c_str()));
    }
    for (const auto& inc : includes) o += inc + "\n";
    o += "\nnamespace " + sanitizeIdent(pkg) + " {\n\n";

    for (const auto& s : vec) {
        o += fmt("// Class %s (0x%X)\n", s.fullName.c_str(), s.size);
        o += fmt("class %s : public %s {\npublic:\n", sanitizeIdent(s.name).c_str(),
                 s.superName.empty() ? "udxrt::UObjectBase"
                                     : sanitizeIdent(s.superName).c_str());
        o += emitMembers(s);
        if (!s.funcs.empty()) {
            o += "\n    // ---- Functions ----\n\n";
            o += emitFunctions(s);
        }
        o += "};\n\n";
    }
    o += "} // namespace " + sanitizeIdent(pkg) + "\n";
    return o;
}

std::string SdkGenerator::emitStructsFile(const std::string& pkg) const {
    const auto& vec = packages_.at(pkg);
    const auto& enums = enumPackages_.count(pkg) ? enumPackages_.at(pkg)
                                                 : std::vector<EnumInfo>{};
    if (vec.empty() && enums.empty()) return {};

    std::string o;
    o += "#pragma once\n";
    o += fmt("// Generated by UnrealDumperX - package \"%s\" (%d structs, %d enums)\n",
             pkg.c_str(), (int)vec.size(), (int)enums.size());
    o += "#include \"../Basic.h\"\n\n";
    o += "namespace " + sanitizeIdent(pkg) + " {\n\n";

    for (const auto& e : enums) {
        o += fmt("// Enum %s\nenum class %s : uint8 {\n", e.fullName.c_str(),
                 sanitizeIdent(e.name).c_str());
        for (const auto& [n, v] : e.values)
            o += fmt("    %s = 0x%02X,\n", memberName(n).c_str(), v);
        o += "};\n\n";
    }

    for (const auto& s : vec) {
        if (s.isClass) continue;
        o += fmt("// Struct %s (0x%X)\n", s.fullName.c_str(), s.size);
        if (!s.superName.empty())
            o += fmt("struct %s : public %s {\n", sanitizeIdent(s.name).c_str(),
                     sanitizeIdent(s.superName).c_str());
        else
            o += fmt("struct %s {\n", sanitizeIdent(s.name).c_str());
        o += emitMembers(s);
        o += "};\n\n";
    }
    o += "} // namespace " + sanitizeIdent(pkg) + "\n";
    return o;
}

void SdkGenerator::writeAll() {
    const std::string root = opts_.outDir + "/SDK";
    const std::string basic = root + "/Basic.h";
    if (writeTextFile(basic, basicHeader())) files_.push_back(basic);

    for (const auto& [pkg, vec] : packages_) {
        const std::string dir = root + "/" + sanitizeIdent(pkg);
        const std::string cls = dir + "/" + sanitizeIdent(pkg) + "_classes.h";
        const std::string str = dir + "/" + sanitizeIdent(pkg) + "_struct.h";
        if (writeTextFile(cls, emitClassesFile(pkg))) files_.push_back(cls);
        const std::string sContent = emitStructsFile(pkg);
        if (!sContent.empty() && writeTextFile(str, sContent)) files_.push_back(str);
    }
}

bool SdkGenerator::generate() {
    if (!objects_.count()) {
        log::error("SDK: nesne dizisi bos");
        return false;
    }
    collect();
    writeAll();
    log::ok(fmt("SDK yazildi: %zu dosya -> %s/SDK", files_.size(),
                opts_.outDir.c_str()));
    return !files_.empty();
}

